const router = require('express').Router()
const admin = require('../controllers/adminController')
const orders = require('../controllers/orderController')
const categories = require('../controllers/categoryController')
const content = require('../controllers/siteContentController')
const reviews = require('../controllers/reviewController')
const contact = require('../controllers/contactController')
const asyncHandler = require('../utils/asyncHandler')
const { requireAuth, requireAdmin } = require('../middleware/auth')

router.use(requireAuth, requireAdmin)
router.get('/dashboard', asyncHandler(admin.dashboard))
router.get('/users', asyncHandler(admin.users))
router.patch('/users/:id', asyncHandler(admin.updateUser))
router.delete('/users/:id', asyncHandler(admin.deleteUser))
router.get('/orders', asyncHandler(orders.adminList))
router.patch('/orders/:id/status', asyncHandler(orders.updateStatus))
router.patch('/orders/:id/payment', asyncHandler(orders.updatePayment))
router.get('/reviews', asyncHandler(reviews.list))
router.delete('/reviews/:id', asyncHandler(reviews.remove))
router.get('/categories', asyncHandler(categories.adminList))
router.post('/categories', asyncHandler(categories.create))
router.patch('/categories/:id', asyncHandler(categories.update))
router.delete('/categories/:id', asyncHandler(categories.remove))
router.get('/content', asyncHandler(content.get))
router.put('/content', asyncHandler(content.update))
router.get('/contact-messages', asyncHandler(contact.adminList))
router.patch('/contact-messages/:id', asyncHandler(contact.update))
router.delete('/contact-messages/:id', asyncHandler(contact.remove))
module.exports = router