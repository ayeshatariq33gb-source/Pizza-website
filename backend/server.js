require('dotenv').config()
const express = require('express')
const cors = require('cors')
const connectDatabase = require('./config/db')
const errorHandler = require('./middleware/errorHandler')

if (!process.env.JWT_SECRET) throw new Error('JWT_SECRET must be configured in backend/.env')

const app = express()
const allowedOrigins = (process.env.CLIENT_ORIGIN || 'http://localhost:5173').split(',').map((origin) => origin.trim())
app.use(cors({ origin: allowedOrigins }))
app.use(express.json({ limit: '1mb' }))
app.use(express.urlencoded({ extended: true }))

app.get('/api/health', (request, response) => response.json({ status: 'ok' }))
app.use('/api/auth', require('./routes/authRoutes'))
app.use('/api/users', require('./routes/userRoutes'))
app.use('/api/pizzas', require('./routes/pizzaRoutes'))
app.use('/api/categories', require('./routes/categoryRoutes'))
app.use('/api/content', require('./routes/siteContentRoutes'))
app.use('/api/contact', require('./routes/contactRoutes'))
app.use('/api/cart', require('./routes/cartRoutes'))
app.use('/api/orders', require('./routes/orderRoutes'))
app.use('/api/reviews', require('./routes/reviewRoutes'))
app.use('/api/admin', require('./routes/adminRoutes'))
app.use((request, response) => response.status(404).json({ message: 'API route not found.' }))
app.use(errorHandler)

const port = process.env.PORT || 5000
connectDatabase()
  .then(() => app.listen(port, () => console.log(`API listening on http://localhost:${port}`)))
  .catch((error) => {
    console.error('Could not start the API:', error.message)
    process.exit(1)
  })